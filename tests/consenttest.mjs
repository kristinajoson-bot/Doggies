import { open } from "./stepsharness.mjs";
const r = []; const check = (n, ok, d = "") => { r.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? "  [" + d + "]" : "")); };
let signups = [];
const setup = async page => { await page.route("**/auth/v1/signup*", route => { signups.push(JSON.parse(route.request().postData() || "{}")); route.fulfill({ status: 200, contentType: "application/json", headers: { "access-control-allow-origin": "*" }, body: JSON.stringify({ id: "u9", email: "new@example.com", identities: [] }) }); }); };
const { page, browser, errors } = await open({ noSession: true, setup });
await page.waitForSelector("input[name=agree]");
let t = await page.innerText("body");
check("sign up shows the privacy checkbox, unticked", /agree to the Walkies privacy policy/.test(t) && !(await page.isChecked("input[name=agree]")));
check("optional marketing box is separate and unticked", (await page.locator("input[name=marketing]").count()) === 1 && !(await page.isChecked("input[name=marketing]")));
await page.click("summary >> text=Read the privacy policy");
check("policy opens in place", /Privacy Act 1988/.test(await page.innerText("body")) && /Spam Act 2003/.test(await page.innerText("body")));
await page.screenshot({ path: "signup.png", fullPage: true });
await page.fill("#name", "Kristina"); await page.fill("#email", "new@example.com"); await page.fill("#password", "password123");
await page.click("form[data-form=auth] button.coral"); await page.waitForTimeout(500);
check("cannot sign up without agreeing", signups.length === 0);
await page.check("input[name=agree]"); await page.check("input[name=marketing]");
await page.click("form[data-form=auth] button.coral"); await page.waitForTimeout(800);
const body = signups[0] || {}, data = body.data || {};
check("sign up sent after agreeing", signups.length === 1);
check("consent time and marketing choice recorded", !!data.privacy_accepted_at && data.marketing_opt_in === true && data.display_name === "Kristina", JSON.stringify(data).slice(0, 120));
check("sign in screen has no consent box", (await page.locator("input[name=agree]").count()) === 0 && /Almost there/.test(await page.innerText("body")));
check("Forgot your password is on the sign-in screen", /Forgot your password/.test(await page.innerText("body")));
check("no page errors", errors.length === 0, errors.join("|"));
console.log(r.filter(Boolean).length + " of " + r.length + " passed");
await browser.close();
