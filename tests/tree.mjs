import { open } from "./stepsharness.mjs";
const out = process.argv[2] || "shots"; const mode = process.argv[3] || "worldcup";
const r = []; const check = (n, ok, d = "") => { r.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? "  [" + d + "]" : "")); };
const { page, browser, errors } = await open({ seed: { 0: 3000 } });
page.on("dialog", d => d.accept());
await page.goto("http://localhost:4174/?preview=" + mode, { waitUntil: "networkidle" }); await page.waitForSelector(".hero");
await page.click("[data-tab=rivals]"); await page.waitForSelector(".ban.camp"); await page.waitForTimeout(500);
await page.click("[data-act=joincamp][data-side=a]"); await page.waitForTimeout(500);
await page.screenshot({ path: out + "/" + mode + "-tile.png", fullPage: false });
await page.click(".ban.camp", { position: { x: 30, y: 24 } }); await page.waitForSelector("[data-act=cupback]"); await page.waitForTimeout(500);
const t = await page.innerText("body");
check("cup opens as its own page, not a flip", (await page.locator(".ban-back").count()) === 0 && /Schedule/.test(t) && /Knockout/.test(t));
check("timeline shows dates for each stage", (await page.locator(".tl .row2").count()) >= 3 && /\d+ – \d+ Oct/.test(t));
const n = await page.locator(".bm").count();
check("bracket tree drawn with connectors", n >= 3 && (await page.locator(".tree svg path").count()) >= 2, "matches=" + n + " paths=" + await page.locator(".tree svg path").count());
check("each tree column shows its dates", (await page.locator(".tree .th span").allInnerTexts()).every(x => /Oct/.test(x)));
await page.screenshot({ path: out + "/" + mode + "-page.png", fullPage: true });
await page.click("[data-act=cupback]"); await page.waitForSelector(".ban.camp");
check("back returns to Challenges", /pick your fight/i.test(await page.innerText("body")));
check("no page errors", errors.length === 0, errors.join("|"));
console.log(r.filter(Boolean).length + " of " + r.length + " passed");
await browser.close();
