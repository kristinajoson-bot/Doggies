import { open } from "./stepsharness.mjs";
const out = process.argv[2] || "shots";
const r = []; const check = (n, ok, d = "") => { r.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? "  [" + d + "]" : "")); };
const { page, browser, errors } = await open({ seed: { 0: 3000 } });
page.on("dialog", d => d.accept());
await page.goto("http://localhost:4174/?preview=quarters", { waitUntil: "networkidle" }); await page.waitForSelector(".hero");
await page.click("[data-tab=rivals]"); await page.waitForSelector(".ban.camp"); await page.waitForTimeout(500);
await page.click("[data-act=joincamp][data-side=a]"); await page.waitForTimeout(500);
await page.screenshot({ path: out + "/q-front.png", fullPage: true });
await page.click(".ban.camp", { position: { x: 30, y: 24 } }); await page.waitForSelector("[data-act=cupback]"); await page.waitForTimeout(500);
check("page: tree has 7 matches over quarter-finals, semi-finals, grand final", (await page.locator(".bm").count()) === 7 && (await page.locator(".tree .th b").allInnerTexts()).join("|") === "Quarter-finals|Semi-finals|Grand final");
await page.click("[data-act=cupback]"); await page.waitForSelector(".ban.camp");
await page.click("[data-tab=packs]");
check("tabs: Walkers, Packs, Challenges, World Cup", /World Cup/i.test(await page.innerText(".chips")) && /Challenges/i.test(await page.innerText(".chips")));
await page.click("[data-bracket=Cup]"); await page.waitForTimeout(500);
await page.screenshot({ path: out + "/q-cup.png", fullPage: true });
await page.click("[data-bracket=Camp]"); await page.waitForTimeout(500);
let t = await page.innerText("body");
check("Challenges tab: everyone ranked with their city, no bracket", /Marco/.test(t) && (await page.locator(".citytag").count()) >= 10 && !/Quarter-finals/i.test(t) && (await page.locator(".lb").count()) === 16);
await page.screenshot({ path: out + "/q-board.png", fullPage: false });
check("no page errors", errors.length === 0, errors.join("|"));
console.log(r.filter(Boolean).length + " of " + r.length + " passed");
await browser.close();
