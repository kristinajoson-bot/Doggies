import { open } from "./stepsharness.mjs";
const out = process.argv[2] || "shots";
const r = []; const check = (n, ok, d = "") => { r.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? "  [" + d + "]" : "")); };
const { page, browser, errors } = await open({ seed: { 0: 3000 } });
page.on("dialog", d => d.accept());
await page.goto("http://localhost:4174/?preview=capitals", { waitUntil: "networkidle" }); await page.waitForSelector(".hero");
await page.click("[data-tab=rivals]"); await page.waitForSelector(".ban.camp"); await page.waitForTimeout(600);
let t = await page.innerText(".ban.camp");
check("front: title and a pick-your-city grid with all 8 capitals", /Capital Cities Challenge/i.test(t) && (await page.locator(".ban.camp button.citypill").count()) === 8 && /Canberra/.test(t) && /Darwin/.test(t) && !/walkers/.test(t), t.replace(/\n/g, " | "));
check("preview is labelled", /preview with demo numbers/i.test(await page.innerText("body")));
await page.screenshot({ path: out + "/cities-front.png", fullPage: true });
await page.click("[data-act=joincamp][data-side=e]"); await page.waitForTimeout(500);
t = await page.innerText(".ban.camp");
check("after joining: You are on Team Adelaide + Invite friends", /You are on Team Adelaide/.test(t) && (await page.locator("[data-act=sharecamp]").count()) === 1);
await page.screenshot({ path: out + "/cities-joined.png", fullPage: true });
await page.click(".ban.camp[data-flip]", { position: { x: 30, y: 24 } }); await page.waitForTimeout(700);
t = await page.innerText(".ban-back");
check("back ranks all 8 cities by steps per walker, Canberra first", (await page.locator(".ban-back .cityrow").count()) === 8 && t.indexOf("Canberra") < t.indexOf("Hobart") && t.indexOf("Hobart") < t.indexOf("Brisbane") && /per walker/.test(t) && (await page.locator(".ban-back .lb").count()) === 0 && !/Show all/.test(t));
await page.screenshot({ path: out + "/cities-back.png", fullPage: true });
await page.click(".ban-back .cityavg >> nth=0"); await page.waitForTimeout(600);
await page.click("[data-tab=packs]"); await page.click("[data-bracket=Camp]"); await page.waitForTimeout(600);
t = await page.innerText("body");
check("leaderboard: Cities standings then walkers tagged with their team", /Cities/.test(t) && /Walkers/.test(t) && (await page.locator(".cityrow").count()) === 8 && /Team Canberra/.test(t) && /Team Adelaide/.test(t) && (await page.locator(".lb").count()) >= 16);
await page.screenshot({ path: out + "/cities-board.png", fullPage: true });
check("no page errors", errors.length === 0, errors.join("|"));
console.log(r.filter(Boolean).length + " of " + r.length + " passed");
await browser.close();
