import { open } from "./stepsharness.mjs";
const out = process.argv[2] || "shots";
const r = []; const check = (n, ok, d = "") => { r.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? "  [" + d + "]" : "")); };
const { page, browser, errors } = await open({ seed: { 0: 3000 } });
page.on("dialog", d => d.accept());
await page.goto("http://localhost:4174/?preview=worldcup", { waitUntil: "networkidle" }); await page.waitForSelector(".hero");
await page.click("[data-tab=rivals]"); await page.waitForSelector(".ban.camp"); await page.waitForTimeout(600);
let t = await page.innerText(".ban.camp");
check("front: World Cup stage, title, both live semi-finals and pick your city", /World Cup/i.test(t) && /Semi-finals/i.test(t) && /City World Cup/i.test(t) && (await page.locator(".ban.camp .mcard").count()) === 2 && (await page.locator(".ban.camp button.citypill").count()) === 8, t.replace(/\n/g, " | "));
await page.screenshot({ path: out + "/wc-front.png", fullPage: true });
await page.click("[data-act=joincamp][data-side=a]"); await page.waitForTimeout(500);
check("joined: You are on Team Sydney", /You are on Team Sydney/.test(await page.innerText(".ban.camp")));
await page.click(".ban.camp", { position: { x: 30, y: 24 } }); await page.waitForSelector("[data-act=cupback]"); await page.waitForTimeout(500);
t = await page.innerText("body");
check("page: schedule, tree, group tables, matches", /Schedule/.test(t) && /Grand final/i.test(t) && (await page.locator(".bm").count()) === 3 && (await page.locator(".gtab:not(.h)").count()) === 8 && /Matches/.test(t));
await page.click("[data-act=cupback]"); await page.waitForSelector(".ban.camp");
await page.click("[data-tab=packs]"); await page.click("[data-bracket=Cup]"); await page.waitForTimeout(500);
t = (await page.innerText("body")).toLowerCase();
check("World Cup tab: knockout then groups", t.indexOf("semi-finals") > -1 && t.indexOf("semi-finals") < t.indexOf("group a") && /grand final/.test(t));
await page.click("[data-bracket=Camp]"); await page.waitForTimeout(500);
check("Challenges tab: everyone with their city, no bracket", (await page.locator(".lb").count()) >= 16 && (await page.locator(".citytag").count()) >= 16 && !/group a/i.test(await page.innerText("body")));
await page.screenshot({ path: out + "/wc-board.png" });
check("no page errors", errors.length === 0, errors.join("|"));
console.log(r.filter(Boolean).length + " of " + r.length + " passed");
await browser.close();
